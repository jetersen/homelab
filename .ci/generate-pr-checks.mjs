import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { parse, stringify } from "yaml";

const checks = {
  runner: ["check-runner.yaml", "Runner image"],
  csharp: ["check-style-csharp.yaml", "C# validation"],
  dnscontrol: ["check-style-dnscontrol.yaml", "DNS compatibility"],
  javascript: ["check-style-javascript.yaml", "JavaScript"],
  python: ["check-style-python.yaml", "Python"],
  rust: ["check-rust.yaml", "Rust validation"],
  upgrade_policy: ["check-upgrade-policy.yaml", "Upgrade policy"],
  dns: ["dnscontrol.yaml", "DNS validation"],
  truenas: ["truenas.yaml", "TrueNAS preview"],
};
const expression = (value) => `\${{ ${value} }}`;
const checkout = {
  uses: "https://github.com/actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1",
  with: { "fetch-depth": 0, "persist-credentials": false },
};
const jobs = {
  changes: {
    "runs-on": "linux-docker",
    "timeout-minutes": 5,
    outputs: Object.fromEntries(
      Object.keys(checks).map((name) => [name, `\${{ steps.select.outputs.${name} }}`]),
    ),
    steps: [
      checkout,
      {
        id: "select",
        env: {
          BASE_SHA: expression("forgejo.event.pull_request.base.sha"),
          HEAD_SHA: expression("forgejo.event.pull_request.head.sha"),
        },
        run: 'python3 .ci/pr-checks.py select "$BASE_SHA" "$HEAD_SHA" >> "$GITHUB_OUTPUT"',
      },
    ],
  },
};
for (const [id, [file, name]] of Object.entries(checks)) {
  const source = parse(await readFile(`.forgejo/workflows/${file}`, "utf8"));
  assert.equal(Object.keys(source.jobs).length, 1, `${file} must define one check`);
  const job = Object.values(source.jobs)[0];
  // Deployment steps belong only to the standalone main/manual workflows.
  job.steps = job.steps.filter((step) => !step.if?.includes("forgejo.ref == 'refs/heads/main'"));
  const condition = `needs.changes.outputs.${id} == 'true'`;
  job.if = job.if ? `\${{ ${condition} && (${job.if}) }}` : `\${{ ${condition} }}`;
  job.name = name;
  job.needs = ["changes"];
  if (source.concurrency) {
    job.concurrency = source.concurrency;
  }
  if (source.defaults) {
    job.defaults = source.defaults;
  }
  jobs[id] = job;
}
jobs.complete = {
  name: "Required PR checks",
  if: expression("always()"),
  needs: ["changes", ...Object.keys(checks)],
  "runs-on": "linux-docker",
  "timeout-minutes": 5,
  steps: [
    {
      env: { CHECK_RESULTS: expression("toJSON(needs)") },
      run: `node --input-type=module <<'PR_CHECK_GATE'\n${await readFile(".ci/pr-checks-gate.mjs", "utf8")}PR_CHECK_GATE\n`,
    },
  ],
};
const generated =
  "# Check jobs generated by .ci/generate-pr-checks.mjs. Edit their source workflows.\n" +
  stringify(
    {
      name: "PR checks",
      on: { pull_request: {} },
      concurrency: { group: `pr-checks-${expression("forgejo.ref")}`, "cancel-in-progress": true },
      jobs,
    },
    { lineWidth: 0 },
  );
const path = ".forgejo/workflows/pr-checks.yaml";
if (process.argv.includes("--check")) {
  assert.equal(await readFile(path, "utf8"), generated, "Run node .ci/generate-pr-checks.mjs");
} else {
  await writeFile(path, generated);
}
